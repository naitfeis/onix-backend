export function helpReply(text: string): string {
  const t = text.toLowerCase();
  if (/^(пока|до\s*свидания|bye)/i.test(t)) {
    return 'Пока! Если понадоблюсь — напишите «Создай товар» или задайте вопрос.';
  }
  if (/^(привет|здравствуй|здравствуйте|хай|hello|hi)/i.test(t)) {
    return [
      'Привет! Я ONIX AI.',
      '',
      'Могу помочь создать товар: напишите «Создай товар».',
      'Также отвечаю, где что находится и как работает гарантия.',
    ].join('\n');
  }
  if (/как\s+продавать/i.test(t)) {
    return [
      'Как продавать на ONIX:',
      '1. Рынок → «Разместить лот» или напишите мне «Создай товар».',
      '2. Укажите название, категорию, цену и количество.',
      '3. После покупки передайте товар в сделке; деньги в Escrow до подтверждения покупателя.',
    ].join('\n');
  }
  if (/гарант|escrow|сейф/i.test(t)) {
    return [
      'Система гарантии (Escrow):',
      '• Покупатель платит — деньги замораживаются.',
      '• Продавец передаёт товар.',
      '• Покупатель подтверждает получение — выплата продавцу (минус 5% комиссии).',
      '• При проблеме — спор / поддержка в заказе.',
    ].join('\n');
  }
  if (/где\s+(что|находится)/i.test(t)) {
    return [
      'Где что находится:',
      '• Рынок — витрина лотов',
      '• Чаты — переписка и ONIX AI',
      '• Сделки — ваши заказы и споры',
      '• Профиль — баланс, залог, мои товары',
      '• Создать — форма нового лота',
    ].join('\n');
  }
  return [
    'Я ONIX AI — помощник платформы (не ChatGPT).',
    '',
    'Команды:',
    '• Создай товар',
    '• Новый товар',
    '',
    'Спросите: как продавать, система гарантии, где что находится.',
  ].join('\n');
}
