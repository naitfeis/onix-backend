export function helpReply(text: string): string {
  const t = text.toLowerCase();
  if (/^(пока|до\s*свидания|bye)/i.test(t)) {
    return 'Пока! Если понадоблюсь — напишите «Создай товар» или задайте вопрос.';
  }
  if (/^(привет|здравствуй|здравствуйте|хай|hello|hi)/i.test(t)) {
    return [
      'Привет! Я ONIX AI.',
      '',
      'Нажмите кнопку ниже или напишите «Создай товар».',
      'Могу рассказать про гарант, вывод и поддержку.',
    ].join('\n');
  }
  if (/как\s+продавать|добавить\s+товар/i.test(t)) {
    return [
      'Как добавить товар на ONIX:',
      '1. Напишите мне «Создай товар» или откройте вкладку «Создать».',
      '2. Укажите название, категорию, подкатегорию, цену и количество.',
      '3. После публикации лот появится на рынке; при покупке деньги уйдут в Escrow.',
    ].join('\n');
  }
  if (/гарант|escrow|сейф/i.test(t)) {
    return [
      'Как работает система гаранта (Escrow):',
      '• Покупатель оплачивает — сумма замораживается на платформе.',
      '• Продавец передаёт товар в сделке.',
      '• Покупатель подтверждает получение — продавцу зачисляется выплата (минус 5%).',
      '• При проблеме откройте спор или поддержку в заказе — деньги не уйдут, пока спор не решён.',
    ].join('\n');
  }
  if (/вывод|сколько\s+ждать|когда\s+прид/i.test(t)) {
    return [
      'Сколько ждать вывод:',
      '• Заявка на вывод создаётся из профиля (Баланс → Вывести).',
      '• Обычно обработка занимает до 24 часов в рабочие дни.',
      '• Залог выводится отдельно: доступна только незамороженная часть.',
      '• Статус смотрите в истории баланса в профиле.',
    ].join('\n');
  }
  if (/поддержк|саппорт|support|жалоб/i.test(t)) {
    return [
      'Как работает поддержка:',
      '• В заказе нажмите «Обратиться в поддержку» или «Открыть спор» — один раз на сделку.',
      '• Администратор подключается к чату покупателя и продавца.',
      '• В карточке «Ваш спор» видно статус и очередь.',
      '• Решение: возврат покупателю или подтверждение продавцу — пишется в чат сделки.',
    ].join('\n');
  }
  if (/где\s+(что|находится)/i.test(t)) {
    return [
      'Где что находится:',
      '• Рынок — витрина лотов',
      '• Чаты — переписка и ONIX AI',
      '• Сделки — ваши заказы и споры',
      '• Профиль — баланс, залог, мои товары',
      '• Создать — форма нового лота',
    ].join('\n');
  }
  return [
    'Я ONIX AI — помощник платформы.',
    '',
    'Быстрые темы:',
    '• Добавить товар',
    '• Как работает система гаранта',
    '• Сколько ждать вывод',
    '• Как работает поддержка',
  ].join('\n');
}
