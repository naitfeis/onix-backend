export function faqAnswer(id: string): string | null {
  return FAQ_ITEMS.find((item) => item.id === id)?.answer ?? null;
}

export function matchFaq(text: string): string | null {
  const q = text.toLowerCase();
  if (/как работает|как пользоваться|что такое onix|как сайт/.test(q)) return faqAnswer('how_site');
  if (/довер|рейтинг|уровень/.test(q)) return faqAnswer('trust_level');
  if (/сейф|эскроу|escrow|заморож/.test(q)) return faqAnswer('escrow');
  if (/гарант/.test(q)) return faqAnswer('warranty');
  if (/отзыв/.test(q)) return faqAnswer('reviews');
  if (/не видн|пропал|тенев|бан лот/.test(q)) return faqAnswer('shadow');
  if (/видео|запис/.test(q)) return faqAnswer('video');
  if (/google|гугл|продавать/.test(q)) return faqAnswer('google_sell');
  if (/тикет|жалоб|поддерж/.test(q)) return faqAnswer('support_ticket');
  return null;
}

