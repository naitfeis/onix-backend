function aboutOnixMenu(): string {
  return [
    'ONIX — безопасный P2P-маркетплейс цифровых товаров с системой гаранта (Escrow).',
    '',
    'Покупатель платит на платформу → продавец передаёт товар → после подтверждения деньги уходят продавцу.',
    '',
    'Что можно сделать:',
    '• Создать лот — напишите «Создай товар» или откройте вкладку «Лот»',
    '• Купить на рынке — деньги в сейфе до подтверждения',
    '• Открыть спор / поддержку — в заказе',
    '• Баланс и залог — в профиле',
    '• Чаты — переписка и я, ONIX AI',
    '',
    'Спросите: гарант · вывод · поддержка · как продавать · где что находится',
  ].join('\n');
}

export function helpReply(text: string): string {
  const t = text.toLowerCase().trim();

  if (/^(пока|до\s*свидания|bye)/i.test(t)) {
    return 'Пока! Если понадоблюсь — напишите «Создай товар» или «О площадке ONIX».';
  }

  if (
    /^(привет|здравствуй|здравствуйте|хай|hello|hi)\b/i.test(t)
    || /как\s+дела|как\s+ты|что\s+нового/i.test(t)
  ) {
    return [
      'Привет! У меня всё отлично — на связи, чтобы помочь с ONIX.',
      '',
      'ONIX — площадка безопасных сделок: рынок лотов, эскроу-гарант, чаты и поддержка.',
      '',
      'Нажмите «О площадке ONIX» или напишите «Создай товар».',
      'Также: гарант · вывод · поддержка.',
    ].join('\n');
  }

  if (
    /о\s+площадке|что\s+такое\s+оникс|что\s+такое\s+onix|про\s+оникс|про\s+onix|оникс\s+это|onix\s+это|меню|о\s+onix|о\s+оникс/i.test(t)
  ) {
    return aboutOnixMenu();
  }

  if (/как\s+продавать|добавить\s+товар/i.test(t)) {
    return [
      'Как добавить товар на ONIX:',
      '1. Напишите «Создай товар» или откройте вкладку «Лот».',
      '2. Укажите название, категорию, подкатегорию, цену и количество.',
      '3. После публикации лот появится на рынке; при покупке деньги уйдут в Escrow.',
      '',
      'Комиссия продажи — 5%.',
    ].join('\n');
  }

  if (/гарант|escrow|сейф/i.test(t)) {
    return [
      'Как работает система гаранта (Escrow):',
      '• Покупатель оплачивает — сумма замораживается на платформе.',
      '• Продавец передаёт товар в сделке.',
      '• Покупатель подтверждает получение — продавцу зачисляется выплата (минус 5%).',
      '• При проблеме откройте спор или поддержку в заказе — деньги не уйдут, пока спор не решён.',
    ].join('\n');
  }

  if (/вывод|сколько\s+ждать|когда\s+прид/i.test(t)) {
    return [
      'Сколько ждать вывод:',
      '• Напишите «Вывести деньги» здесь, в ONIX AI — укажу сумму, способ и реквизиты.',
      '• Или создайте заявку из профиля (Баланс → Вывести).',
      '• Обычно обработка занимает до 24 часов в рабочие дни.',
      '• Залог выводится отдельно: доступна только незамороженная часть.',
    ].join('\n');
  }

  if (/поддержк|саппорт|support|жалоб/i.test(t)) {
    return [
      'Как работает поддержка:',
      '• Напишите «Написать в поддержку» здесь, в ONIX AI — обращение попадёт в жалобы админу, ответ придёт сюда.',
      '• В заказе: «Обратиться в поддержку» или «Открыть спор» — один раз на сделку.',
      '• По спору администратор подключается к чату сделки.',
      '• Решение по сделке: возврат покупателю или подтверждение продавцу.',
    ].join('\n');
  }

  if (/где\s+(что|находится)|навигац|разделы/i.test(t)) {
    return [
      'Где что находится:',
      '• Рынок — витрина лотов',
      '• Сделки — заказы и споры',
      '• Лот — создать объявление',
      '• Чаты — переписка и ONIX AI',
      '• Профиль — баланс, залог, мои товары, аналитика',
    ].join('\n');
  }

  if (/комисс|сколько\s+берет|процент/i.test(t)) {
    return [
      'Комиссия ONIX:',
      '• С продажи — 5% (выплата продавцу = сумма − комиссия).',
      '• Покупка на рынке — полная цена лота уходит в эскроу.',
    ].join('\n');
  }

  if (/залог|депозит/i.test(t)) {
    return [
      'Залог продавца:',
      '• Отдельный кошелёк в профиле — показывает покупателям серьёзность продавца.',
      '• Пополнить можно с основного баланса.',
      '• После сделки часть залога может заморозиться на несколько дней.',
      '• Вывести можно только доступную (незамороженную) часть.',
    ].join('\n');
  }

  return [
    'Я ONIX AI — помощник площадки ONIX.',
    '',
    'Быстрые темы:',
    '• О площадке ONIX',
    '• Добавить товар',
    '• Как работает система гаранта',
    '• Сколько ждать вывод',
    '• Как работает поддержка',
  ].join('\n');
}
